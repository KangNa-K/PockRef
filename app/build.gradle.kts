import com.android.build.api.dsl.ApkSigningConfig
import java.util.Properties

android {
    namespace = "com.pockref.app"
    compileSdk = 34

    defaultConfig {
        applicationId = "com.pockref.app"
        minSdk = 24
        targetSdk = 34
        versionCode = 3
        versionName = "1.2.0"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        vectorDrawables {
            useSupportLibrary = true
        }
    }

    // Release signing is loaded from `keystore.properties` (gitignored). The
    // file sits at the project root and contains:
    //   storeFile=release.keystore
    //   storePassword=...
    //   keyAlias=pockref
    //   keyPassword=...
    // To rotate: `keytool -genkey ... -keystore release.keystore` and update
    // the properties file. NEVER commit the properties or the keystore.
    val keystoreProps = rootProject.file("keystore.properties")
    val signingConfigRelease: ApkSigningConfig? = if (keystoreProps.exists()) {
        val props = Properties()
        keystoreProps.inputStream().use { props.load(it) }
        signingConfigs.create("release") {
            storeFile = rootProject.file(props.getProperty("storeFile"))
            storePassword = props.getProperty("storePassword")
            keyAlias = props.getProperty("keyAlias")
            keyPassword = props.getProperty("keyPassword")
        }
    } else {
        null
    }

    buildTypes {
        debug {
            // Debug builds stay readable for Android Studio attach / logcat /
            // debugger; running R8 here caused the install-and-crash on first
            // launch because reflection-driven Compose init paths weren't
            // fully covered by the keep rules. R8 is validated in release.
            isMinifyEnabled = false
            isShrinkResources = false
        }
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )
            if (signingConfigRelease != null) {
                signingConfig = signingConfigRelease
            }
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    kotlinOptions {
        jvmTarget = "17"
